#!/usr/bin/env node
// DEC-286 — which message namespaces each AREA of the product sends to the browser.
//
//   node scripts/client-scopes.mjs           # rewrite src/messages/client-scopes.ts
//   node scripts/client-scopes.mjs --check   # exit 1 if the file is stale (tests/unit/client-scopes.test.ts runs this)
//
// Every page used to send the WHOLE catalogue — all 37 namespaces, ~300 KB of text in the HTML of a sign-in page —
// because the root `NextIntlClientProvider` was given no `messages` and so passed them all. Now each area's provider
// passes only the namespaces its files name in `useTranslations("…")`, and the lists are COMPUTED here from the import
// graph rooted at the area's routes, never written by hand: a component added to a page is in its area's graph the day
// it is imported, and a stale list fails CI before a page can render a key instead of its text.
//
// It over-approximates on purpose: every `useTranslations` in a reachable file counts, server or client.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const APP = join(SRC, "app", "[locale]");
const OUT = join(SRC, "messages", "client-scopes.ts");

/** An area: the routes whose layout carries its provider, minus the nested areas that carry their own. */
export const AREAS = {
  public: { roots: [APP], except: [join(APP, "app"), join(APP, "(dev)")] },
  member: { roots: [join(APP, "app")], except: [join(APP, "app", "admin"), join(APP, "app", "platform")] },
  admin: { roots: [join(APP, "app", "admin")], except: [] },
  platform: { roots: [join(APP, "app", "platform")], except: [] },
  dev: { roots: [join(APP, "(dev)")], except: [] },
};

function filesUnder(path, except) {
  if (except.some((e) => path === e)) return [];
  if (!statSync(path).isDirectory()) return /\.(tsx?|mjs)$/.test(path) ? [path] : [];
  return readdirSync(path).flatMap((name) => filesUnder(join(path, name), except));
}

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = join(SRC, spec.slice(2));
  else if (spec.startsWith(".")) base = resolve(dirname(from), spec);
  else return null;
  for (const candidate of [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

const sources = new Map();
const read = (file) => sources.get(file) ?? sources.set(file, readFileSync(file, "utf8")).get(file);

function importsOf(file) {
  const source = read(file);
  const specs = [
    ...[...source.matchAll(/^\s*(?:import|export)\s+(?!type\b)[^;]*?\bfrom\s+["']([^"']+)["']/gm)].map((m) => m[1]),
    ...[...source.matchAll(/^\s*import\s+["']([^"']+)["']/gm)].map((m) => m[1]),
    ...[...source.matchAll(/\bimport\(\s*["']([^"']+)["']\s*\)/g)].map((m) => m[1]),
  ];
  return specs.map((s) => resolveImport(file, s)).filter((f) => f !== null);
}

/** `useTranslations("a.b")` → "a.b"; a call without a literal namespace makes the whole catalogue the answer. */
function namespacesOf(file) {
  const source = read(file);
  const out = [];
  for (const m of source.matchAll(/\buseTranslations\(\s*([^)]*?)\s*\)/g)) {
    const arg = m[1];
    const literal = arg.match(/^["']([^"']+)["']$/);
    out.push(literal ? literal[1] : "*");
  }
  return out;
}

/** The smallest set of paths covering every namespace named — "a" covers "a.b". */
function minimal(paths) {
  if (paths.includes("*")) return ["*"];
  const sorted = [...new Set(paths)].sort();
  return sorted.filter((p) => !sorted.some((q) => q !== p && p.startsWith(`${q}.`)));
}

export function computeScopes() {
  const scopes = {};
  for (const [name, { roots, except }] of Object.entries(AREAS)) {
    const seen = new Set();
    const queue = roots.flatMap((r) => filesUnder(r, except));
    while (queue.length) {
      const file = queue.pop();
      if (seen.has(file)) continue;
      seen.add(file);
      queue.push(...importsOf(file));
    }
    scopes[name] = minimal([...seen].flatMap(namespacesOf));
  }
  return scopes;
}

export function render(scopes) {
  const lines = Object.entries(scopes).map(([k, v]) => `  ${k}: [${v.map((p) => JSON.stringify(p)).join(", ")}],`);
  return `// GENERATED by \`node scripts/client-scopes.mjs\` — do not edit (DEC-286). Each area's message namespaces, computed
// from the import graph of its routes; \`tests/unit/client-scopes.test.ts\` fails when this is stale.
export const CLIENT_SCOPES = {
${lines.join("\n")}
} as const;

export type ClientScope = keyof typeof CLIENT_SCOPES;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(computeScopes());
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== text) {
      console.error(`${relative(ROOT, OUT)} is stale — run \`node scripts/client-scopes.mjs\``);
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${relative(ROOT, OUT)}`);
  }
}
